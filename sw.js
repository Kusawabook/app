// Bump CACHE whenever a shell file changes, so phones drop the old copy.
const CACHE = 'kasuwabook-v1';
const SHELL = ['./', 'index.html', 'styles.css', 'app.js', 'manifest.webmanifest', 'icon.svg'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

// Open from the phone's copy first, so the app starts instantly on bad data,
// and refresh that copy in the background whenever the network answers.
self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;

  const fresh = fetch(request).then((response) => {
    if (response.ok) {
      const copy = response.clone();
      caches.open(CACHE).then((cache) => cache.put(request, copy));
    }
    return response;
  });
  event.waitUntil(fresh.catch(() => {}));

  event.respondWith(
    caches.match(request, { ignoreSearch: true })
      .then((cached) => cached || fresh.catch(() => Response.error()))
  );
});
